#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

LIMINE_VERSION="12.10.0"
LIMINE_SHA256="365ba8785d4e4b55c3368738a642681b31f606afec9f77179e07fc26ebe841e2"
PROTOCOL_COMMIT="877c2d4c50e170575f8b8e7fbf7b8fa89b1dc157"

mkdir -p deps build release
# The exact Limine protocol header is vendored in kernel/include/limine.h.
# Keep the source commit recorded here for reproducibility.
curl --fail --location --retry 3 \
  "https://github.com/Limine-Bootloader/Limine/releases/download/v${LIMINE_VERSION}/limine-binary.tar.gz" \
  -o build/limine-binary.tar.gz
echo "${LIMINE_SHA256}  build/limine-binary.tar.gz" | sha256sum --check -

rm -rf build/limine-binary
tar -xzf build/limine-binary.tar.gz -C build
make -C build/limine-binary

# Limine embeds its HDD BIOS boot image into limine-bios-hdd.h for the host
# installer. Reconstruct the exact generated byte array as a module payload.
python3 - <<'PY'
import re
from pathlib import Path
header = Path("build/limine-binary/limine-bios-hdd.h")
if not header.is_file():
    raise SystemExit("Limine BIOS HDD image header was not generated")
values = re.findall(r"0x([0-9a-fA-F]{2})", header.read_text())
if not values:
    raise SystemExit("Limine BIOS HDD image header contains no byte array")
image = bytes(int(value, 16) for value in values)
if len(image) < 512 or image[510:512] != b"\x55\xaa":
    raise SystemExit("Extracted Limine BIOS HDD image has no valid MBR signature")
Path("build/limine-binary/limine-bios-hdd.bin").write_bytes(image)
print(f"Extracted Limine BIOS HDD image: {len(image)} bytes")
PY

# Build the pinned Mbed TLS 1.3 client as freestanding kernel objects.
# Cryptographic RNG, RTC time, and allocator callbacks are provided by Nexus.
sh toolchain/fetch-mbedtls.sh
sh toolchain/fetch-ca-bundle.sh
cmake -S build/deps/mbedtls-4.1.2 -B build/deps/mbedtls-kernel-build \
  -DENABLE_TESTING=OFF -DENABLE_PROGRAMS=OFF \
  -DMBEDTLS_CONFIG_SET="MBEDTLS_PSA_CRYPTO_EXTERNAL_RNG;MBEDTLS_PLATFORM_TIME_ALT;MBEDTLS_PLATFORM_GMTIME_R_ALT;MBEDTLS_PLATFORM_MS_TIME_ALT;MBEDTLS_PLATFORM_MEMORY;MBEDTLS_SSL_PROTO_TLS1_3" \
  -DMBEDTLS_CONFIG_UNSET="MBEDTLS_PSA_BUILTIN_GET_ENTROPY;MBEDTLS_NET_C;MBEDTLS_TIMING_C;MBEDTLS_SELF_TEST;MBEDTLS_FS_IO;MBEDTLS_DEBUG_C;MBEDTLS_AESNI_C;MBEDTLS_PSA_ITS_FILE_C;MBEDTLS_PSA_CRYPTO_STORAGE_C" \
  -DCMAKE_C_FLAGS="-O2 -D_GNU_SOURCE -U_FORTIFY_SOURCE -D_FORTIFY_SOURCE=0 -include stdint.h -ffreestanding -fno-builtin -fno-stack-protector -fno-pic -fno-pie -fno-asynchronous-unwind-tables -fno-unwind-tables -m64 -march=x86-64 -mno-red-zone -mno-mmx -mno-sse -mno-sse2 -mgeneral-regs-only -mcmodel=kernel"
cmake --build build/deps/mbedtls-kernel-build --parallel 2
make -C kernel clean all NEXUS_TLS=1

# Ship first-party Nexus-native applications as a checksummed read-only system
# pack. These static x86-64 ELF programs have no host OS dependencies.
make -C sdk clean all CC="${NEXUS_SDK_CC:-gcc}"
python3 build/make-system-pack.py \
  --output build/system-pack/NEXUS-SYSTEM.NXP \
  --file NEXUS-README.TXT=system/README.TXT \
  --file NEXUS-APPS.TXT=system/APPS.TXT \
  --file KINETIC.ELF=sdk/build/kinetic_demo.elf \
  --file GAMEPAD.ELF=sdk/build/gamepad_demo.elf \
  --file AUDIO.ELF=sdk/build/audio_demo.elf \
  --file PIE.ELF=sdk/build/pie_demo.elf

ISO_ROOT="$ROOT/build/iso-root"
rm -rf "$ISO_ROOT"
mkdir -p "$ISO_ROOT/boot/limine" "$ISO_ROOT/EFI/BOOT" "$ISO_ROOT/NEXUS"
cp build/nexus-kernel.elf "$ISO_ROOT/boot/nexus-kernel.elf"
cp boot/limine.conf "$ISO_ROOT/boot/limine/limine.conf"
cp build/limine-binary/limine-bios.sys "$ISO_ROOT/boot/limine/"
cp build/limine-binary/limine-bios-hdd.bin "$ISO_ROOT/boot/limine/"
cp build/limine-binary/limine-bios-cd.bin "$ISO_ROOT/boot/limine/"
cp build/limine-binary/limine-uefi-cd.bin "$ISO_ROOT/boot/limine/"
cp build/limine-binary/BOOTX64.EFI "$ISO_ROOT/EFI/BOOT/"
cp build/system-pack/NEXUS-SYSTEM.NXP "$ISO_ROOT/NEXUS/SYSTEM.NXP"
# Keep installer payload paths identical to the Limine module request order.
test -s "$ISO_ROOT/EFI/BOOT/BOOTX64.EFI"
test -s "$ISO_ROOT/boot/limine/limine-bios.sys"
test -s "$ISO_ROOT/boot/limine/limine-bios-hdd.bin"
test -s "$ISO_ROOT/boot/nexus-kernel.elf"
test -s "$ISO_ROOT/NEXUS/SYSTEM.NXP"
test "$(stat -c %s "$ISO_ROOT/NEXUS/SYSTEM.NXP")" -le 2097152
grep -q 'module_path: boot():/NEXUS/SYSTEM.NXP' "$ISO_ROOT/boot/limine/limine.conf"

xorriso -as mkisofs \
  -R -r -J \
  -b boot/limine/limine-bios-cd.bin \
  -no-emul-boot -boot-load-size 4 -boot-info-table \
  --efi-boot boot/limine/limine-uefi-cd.bin \
  -efi-boot-part --efi-boot-image --protective-msdos-label \
  "$ISO_ROOT" \
  -o release/NexusOS-OriginalKernel-x86_64.iso

build/limine-binary/limine bios-install release/NexusOS-OriginalKernel-x86_64.iso

(
  cd release
  sha256sum NexusOS-OriginalKernel-x86_64.iso > SHA256SUMS.txt
  sha256sum --check SHA256SUMS.txt
)
file release/NexusOS-OriginalKernel-x86_64.iso
