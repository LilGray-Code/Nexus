static void test_multiple_keyboard_report_ids(void) {
    struct nexus_usb_hid_generic_multi_layout multi = {0};
    assert(usb_hid_generic_parse_descriptor_multi(
        two_keyboard_report_ids, sizeof(two_keyboard_report_ids), &multi));
    assert(multi.report_count == 2U);
    assert(multi.max_report_bytes == 9U);
    assert(multi.reports[0].report_id == 1U);
    assert(multi.reports[1].report_id == 2U);
    assert(multi.reports[0].input_bytes == 8U);
    assert(multi.reports[1].input_bytes == 8U);

    const uint8_t report1[9] = {1U,0x01U,0U,0x04U,0U,0U,0U,0U,0U};
    const uint8_t report2[9] = {2U,0x02U,0U,0x05U,0U,0U,0U,0U,0U};
    uint8_t decoded[8] = {0U};
    assert(usb_hid_generic_decode_keyboard_multi(
        &multi, report1, sizeof(report1), decoded));
    assert(decoded[0] == 0x01U && decoded[2] == 0x04U);
    assert(usb_hid_generic_decode_keyboard_multi(
        &multi, report2, sizeof(report2), decoded));
    assert(decoded[0] == 0x02U && decoded[2] == 0x05U);

    const uint8_t unknown_id[9] = {3U,0U,0U,0U,0U,0U,0U,0U,0U};
    assert(!usb_hid_generic_decode_keyboard_multi(
        &multi, unknown_id, sizeof(unknown_id), decoded));
}

static void test_rejects_implicit_report_zero_in_numbered_interface(void) {
    const uint8_t descriptor[] = {
        0x05,0x01, 0x09,0x06, 0xA1,0x01,
        /* First input report is unnumbered. */
        0x05,0x07, 0x19,0xE0, 0x29,0xE7,
        0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x08, 0x81,0x02,
        0x75,0x08, 0x95,0x01, 0x81,0x01,
        0x19,0x00, 0x29,0x65, 0x15,0x00, 0x25,0x65,
        0x75,0x08, 0x95,0x06, 0x81,0x00,
        /* A later numbered input report makes this interface invalid. */
        0x85,0x01,
        0x05,0x07, 0x19,0xE0, 0x29,0xE7,
        0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x08, 0x81,0x02,
        0x75,0x08, 0x95,0x01, 0x81,0x01,
        0x19,0x00, 0x29,0x65, 0x15,0x00, 0x25,0x65,
        0x75,0x08, 0x95,0x06, 0x81,0x00,
        0xC0
    };
    struct nexus_usb_hid_generic_multi_layout multi = {0};
    assert(!usb_hid_generic_parse_descriptor_multi(
        descriptor, sizeof(descriptor), &multi));
}

static void test_report_ids_across_global_push_pop(void) {
    const uint8_t descriptor[] = {
        0x05,0x01, 0x09,0x06, 0xA1,0x01,
        0x85,0x01, 0xA4, 0x85,0x02,
        0x05,0x07, 0x19,0xE0, 0x29,0xE7,
        0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x08, 0x81,0x02,
        0x75,0x08, 0x95,0x01, 0x81,0x01,
        0x19,0x00, 0x29,0x65, 0x15,0x00, 0x25,0x65,
        0x75,0x08, 0x95,0x06, 0x81,0x00,
        0xB4,
        0x05,0x07, 0x19,0xE0, 0x29,0xE7,
        0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x08, 0x81,0x02,
        0x75,0x08, 0x95,0x01, 0x81,0x01,
        0x19,0x00, 0x29,0x65, 0x15,0x00, 0x25,0x65,
        0x75,0x08, 0x95,0x06, 0x81,0x00,
        0xC0
    };
    struct nexus_usb_hid_generic_multi_layout multi = {0};
    assert(usb_hid_generic_parse_descriptor_multi(
        descriptor, sizeof(descriptor), &multi));
    assert(multi.report_count == 2U);
    uint8_t decoded[8] = {0U};
    const uint8_t report1[9] = {1U,0x01U,0U,0x04U,0U,0U,0U,0U,0U};
    const uint8_t report2[9] = {2U,0x02U,0U,0x05U,0U,0U,0U,0U,0U};
    assert(usb_hid_generic_decode_keyboard_multi(
        &multi, report1, sizeof(report1), decoded));
    assert(decoded[0] == 0x01U && decoded[2] == 0x04U);
    assert(usb_hid_generic_decode_keyboard_multi(
        &multi, report2, sizeof(report2), decoded));
    assert(decoded[0] == 0x02U && decoded[2] == 0x05U);
}

static void test_high_resolution_mouse_report_id(void) {
    struct nexus_usb_hid_generic_multi_layout multi = {0};
    assert(usb_hid_generic_parse_descriptor_multi(
        high_resolution_mouse_report_id,
        sizeof(high_resolution_mouse_report_id), &multi));
    assert(multi.report_count == 1U);
    assert(multi.max_report_bytes == 13U);
    assert(multi.reports[0].kind == NEXUS_USB_HID_GENERIC_MOUSE);
    assert(multi.reports[0].report_id == 1U);
    assert(multi.reports[0].x_size == 16U);
    assert(multi.reports[0].y_size == 16U);
    assert(multi.reports[0].wheel_size == 16U);
    assert(multi.reports[0].horizontal_wheel_size == 16U);
    assert(multi.reports[0].button_count == 32U);

    /* Report ID 1, buttons 1/3/32, X=300, Y=-300,
     * vertical wheel=512 and horizontal AC Pan=-256. */
    const uint8_t report[13] = {
        1U, 0x05U, 0x00U, 0x00U, 0x80U, 0x2CU, 0x01U,
        0xD4U, 0xFEU, 0x00U, 0x02U, 0x00U, 0xFFU
    };
    struct nexus_usb_mouse_event event = {0};
    assert(usb_hid_generic_decode_mouse_multi(
        &multi, report, sizeof(report), &event));
    assert(event.buttons == 0x80000005U);
    assert(event.dx == 300);
    assert(event.dy == 300);
    assert(event.wheel == 512);
    assert(event.horizontal_wheel == -256);

    const uint8_t unknown_report[13] = {
        2U,0U,0U,0U,0U,0U,0U,0U,0U,0U,0U,0U,0U
    };
    assert(!usb_hid_generic_decode_mouse_multi(
        &multi, unknown_report, sizeof(unknown_report), &event));
}

